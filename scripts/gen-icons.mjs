import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { ICON_NAMES } from '../src/icon-names.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = path.join(root, 'node_modules', 'lucide-static', 'icons');
const out = {};

for (const name of ICON_NAMES) {
  const raw = await readFile(path.join(iconsDir, `${name}.svg`), 'utf8');
  const match = raw.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  if (!match) throw new Error(`Cannot parse ${name}`);
  out[name] = match[1].replace(/<!--[\s\S]*?-->/g, '').trim();
}

const banner = '/* Generated by scripts/gen-icons.mjs. Icons from Lucide (ISC). */\n';
const body = 'export default ' + JSON.stringify(out, null, 2) + ';\n';
await mkdir(path.join(root, 'src'), { recursive: true });
await writeFile(path.join(root, 'src', 'icons.generated.js'), banner + body);
console.log(`generated ${Object.keys(out).length} icons`);
